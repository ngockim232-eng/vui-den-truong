/**
 * Parse optional explicit gender suffix like "Hồ Văn Tùng - Nam" or "Hồ Thị Mai (Nữ)"
 * and fall back to smart Vietnamese / Ca Dong name inference.
 */
export function parseNameAndGender(rawLine: string): {
  name: string;
  gender: StudentGender;
  explicit: boolean;
} {
  let clean = rawLine
    .replace(/^\s*(?:\d+\s*[.)\-:/]|[-•*+]\s*)+/, '')
    .replace(/\s+/g, ' ')
    .trim();

  // Check explicit suffix: "- Nam", "(Nữ)", "| Nam", "/ Nữ"
  const suffixMatch = clean.match(
    /(?:[\s\-–—|(/]+)(nam|nữ|nu|trai|gái|gai)\s*\)?$/i,
  );
  if (suffixMatch) {
    const token = suffixMatch[1].toLowerCase();
    const stripped = clean.slice(0, suffixMatch.index).trim();
    if (stripped.length > 0) {
      const gender: StudentGender =
        token === 'nữ' || token === 'nu' || token === 'gái' || token === 'gai'
          ? 'female'
          : 'male';
      return { name: stripped, gender, explicit: true };
    }
  }

  return {
    name: clean,
    gender: inferGenderFromName(clean),
    explicit: false,
  };
}

export function inferGenderFromName(fullName: string): StudentGender {
  const parts = fullName
    .trim()
    .toLowerCase()
    .split(/\s+/)
    .filter(Boolean);

  if (parts.length === 0) return 'male';

  // Strong middle-name signals ("Thị" vs "Văn")
  const middleParts = parts.slice(1, -1);
  if (middleParts.some((p) => p === 'thị' || p === 'thi')) return 'female';
  if (middleParts.some((p) => p === 'văn' || p === 'van')) return 'male';

  const given = parts[parts.length - 1];
  if (FEMALE_GIVEN_NAMES.has(given) && !MALE_GIVEN_NAMES.has(given)) {
    return 'female';
  }
  if (MALE_GIVEN_NAMES.has(given) && !FEMALE_GIVEN_NAMES.has(given)) {
    return 'male';
  }

  if (middleParts.some((p) => FEMALE_MIDDLE_TOKENS.has(p))) return 'female';
  if (middleParts.some((p) => MALE_MIDDLE_TOKENS.has(p))) return 'male';

  if (FEMALE_GIVEN_NAMES.has(given)) return 'female';
  return 'male';
}
