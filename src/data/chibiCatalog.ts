export const MALE_PRESETS = CHIBI_PRESETS.filter((p) => p.gender === 'male');
export const FEMALE_PRESETS = CHIBI_PRESETS.filter((p) => p.gender === 'female');

const PRESET_MAP = new Map<string, ChibiPreset>(
  CHIBI_PRESETS.map((p) => [p.id, p]),
);

export function getChibiPreset(
  presetId: string | undefined,
  gender: StudentGender = 'male',
  fallbackIndex = 0,
): ChibiPreset {
  if (presetId) {
    const found = PRESET_MAP.get(presetId);
    if (found && found.gender === gender) return found;
  }
  const pool = gender === 'female' ? FEMALE_PRESETS : MALE_PRESETS;
  return pool[Math.abs(fallbackIndex) % pool.length];
}

export function getChibiPresetAny(presetId: string | undefined): ChibiPreset | undefined {
  return presetId ? PRESET_MAP.get(presetId) : undefined;
}

export function cyclePresetForGender(
  currentPresetId: string | undefined,
  gender: StudentGender,
): ChibiPreset {
  const pool = gender === 'female' ? FEMALE_PRESETS : MALE_PRESETS;
  const idx = pool.findIndex((p) => p.id === currentPresetId);
  return pool[(idx + 1) % pool.length];
}

